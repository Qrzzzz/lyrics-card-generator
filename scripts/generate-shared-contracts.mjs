import { readFile, writeFile } from "node:fs/promises";

const schema = JSON.parse(await readFile("shared/card-style-schema.json", "utf8"));
function fieldType(field) {
  if (field.values) return field.values.map((value) => JSON.stringify(value)).join(" | ");
  if (field.ref) return field.ref;
  return field.type;
}
const source = "// Generated by scripts/generate-shared-contracts.mjs; edit card-style-schema.json.\n" +
  Object.entries(schema.definitions).map(([name, definition]) =>
    `export type ${name} = {\n${Object.entries(definition.fields).map(([key, field]) =>
      `  ${key}${field.optional ? "?" : ""}: ${fieldType(field)};`).join("\n")}\n};\n`
  ).join("\n");
const outputs = new Map([["shared/card-style.generated.ts", source]]);
// Legacy JSON paths remain compatible, but never become a second editable source.
for (const name of ["resource-budgets.json", "support-addresses.json"]) {
  outputs.set(`electron/${name}`, await readFile(`shared/${name}`, "utf8"));
}
const budgets = JSON.parse(await readFile("shared/resource-budgets.json", "utf8"));
const preload = await readFile("electron/preload.js", "utf8");
const generatedLimits = "// BEGIN GENERATED SHARED LIMITS\nconst MAX_CLIPBOARD_IMAGE_ENCODED_BYTES = " + budgets.clipboardImage.encodedBytes + ";\n// END GENERATED SHARED LIMITS";
const region = /\/\/ BEGIN GENERATED SHARED LIMITS[\s\S]*?\/\/ END GENERATED SHARED LIMITS/;
if (!region.test(preload)) throw new Error("Missing generated sandbox limits region");
outputs.set("electron/preload.js", preload.replace(region, generatedLimits));
for (const [file, content] of outputs) {
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== content.replaceAll("\r\n", "\n")) throw new Error(`Stale shared contract: ${file}`);
  } else await writeFile(file, content);
}
console.log(`Shared contract ${process.argv.includes("--check") ? "freshness verified" : "types generated"}.`);
