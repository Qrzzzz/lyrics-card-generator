const assert = require("node:assert/strict");
const { EventEmitter } = require("node:events");
const { createImageDownloadMonitor } = require("../electron/image-download-monitor");
const session = new EventEmitter();
const window = new EventEmitter();
const results = [];
window.isDestroyed = () => false;
window.webContents = { session, isDestroyed: () => false, send: (channel, result) => results.push({ channel, ...result }) };
const monitor = createImageDownloadMonitor(window);
const url = "data:image/png;base64,AA==";
const item = (fileName = "card.png", dataUrl = url) => Object.assign(new EventEmitter(), { getURL: () => dataUrl, getFilename: () => fileName });
assert.equal(monitor.prepare("export-1", "card.png", url), true);
const foreign = item();
session.emit("will-download", {}, foreign, {});
foreign.emit("done", {}, "interrupted");
assert.equal(results.length, 0, "another renderer must not consume the reservation");
const unrelated = item("other.png");
session.emit("will-download", {}, unrelated, window.webContents);
assert.equal(unrelated.listenerCount("done"), 0);
const differentBytes = item("card.png", "data:image/png;base64,AQ==");
session.emit("will-download", {}, differentBytes, window.webContents);
assert.equal(differentBytes.listenerCount("done"), 0, "same filename with different bytes must not match");
const failed = item();
session.emit("will-download", {}, failed, window.webContents);
failed.emit("done", {}, "interrupted");
assert.deepEqual(results.at(-1), { channel: "lyrics-card:image-download-result", id: "export-1", state: "interrupted" });
for (const [id, state] of [["export-2", "completed"], ["export-3", "cancelled"]]) {
  assert.equal(monitor.prepare(id, "card.png", url), true);
  const download = item();
  session.emit("will-download", {}, download, window.webContents);
  download.emit("done", {}, state);
  assert.equal(results.at(-1).state, state);
  assert.equal(results.at(-1).id, id);
}
assert.equal(monitor.prepare("bad", "card.png", url), false);
assert.equal(monitor.prepare("export-4", "card.png", "https://example.com/card.png"), false);
assert.equal(monitor.prepare("export-4", "card.png", url), true);
const active = item();
session.emit("will-download", {}, active, window.webContents);
window.emit("closed");
assert.equal(session.listenerCount("will-download"), 0);
assert.equal(active.listenerCount("done"), 0);
console.log("Native image download monitor: ownership, byte identity, failed/completed/cancelled results and cleanup passed.");
