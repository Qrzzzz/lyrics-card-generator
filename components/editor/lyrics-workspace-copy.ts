export function getLyricsWorkspaceCopy(locale: Locale) {
  return COPY[locale];
}

export function formatLyricsWorkspaceCopy(
  template: string,
  values: Record<string, string | number>
) {
  return template.replace(/\{(\w+)\}/gu, (match, key: string) => (
    values[key] === undefined ? match : String(values[key])
  ));
}
